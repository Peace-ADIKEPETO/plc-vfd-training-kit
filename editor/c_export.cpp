#include "c_export.h"

QString imageToCHeader(const QByteArray &image, const QString &sourceName)
{
    if (image.isEmpty()) return QString();

    QString src = sourceName;
    src.replace("*/", "* /");                      // a file name must not close the comment

    QString s;
    s += "/* ladder_program.h - generated by the ladder editor";
    if (!src.isEmpty()) s += " from " + src;
    s += ".\n * Do not edit: export again from the editor. */\n";
    s += "#ifndef LADDER_PROGRAM_H\n#define LADDER_PROGRAM_H\n\n";
    s += "#include <stdint.h>\n\n";
    s += QString("#define LADDER_PROGRAM_SIZE %1\n\n").arg(image.size());
    s += "static const uint8_t ladder_program[LADDER_PROGRAM_SIZE] = {\n";

    const int n = image.size();
    for (int i = 0; i < n; ++i) {
        if (i % 12 == 0) s += "    ";
        const uint8_t v = static_cast<uint8_t>(image[i]);
        s += "0x" + QString("%1").arg(v, 2, 16, QChar('0')).toUpper();
        if (i < n - 1) s += ",";
        s += (i % 12 == 11 || i == n - 1) ? "\n" : " ";
    }
    s += "};\n\n#endif /* LADDER_PROGRAM_H */\n";
    return s;
}